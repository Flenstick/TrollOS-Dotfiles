# Cyrillic for Jacquard 12, drawn on its pixel grid (1 px = 60 units, baseline row 0).
# Each glyph: rows from y=11 (cap top) down to y=-3; the width of a row is the advance.
# '#' = ink. Lowercase live in rows 7..0 (x-height 8), ascenders to 10, descenders to -3.

def G(*rows):
    rows = [r for r in rows]
    w = max(len(r) for r in rows)
    return [r.ljust(w, '.') for r in rows]

# helpers: a glyph given only some rows; others blank
def g(width, top, rows):
    """Rows y = 14 … -3; `top`: the y of the first row given (11 = cap top, 7 = x-height top)."""
    out = []
    for y in range(14, -4, -1):
        i = top - y
        out.append(rows[i].ljust(width, '.') if 0 <= i < len(rows) else '.' * width)
    return out


def pad(rows):
    return rows

